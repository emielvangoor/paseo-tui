#!/usr/bin/env sh
# Writes the package-manager manifests for a release into dist/pkg/, using the hashes in dist/checksums.txt:
#   dist/pkg/homebrew/paseo-tui.rb          Homebrew formula (macOS and Linux)
#   dist/pkg/scoop/paseo-tui.json           Scoop manifest (Windows)
#   dist/pkg/aur/PKGBUILD, .SRCINFO         AUR package paseo-tui-bin (Arch)
# Usage: packaging/render.sh v0.2.1
set -eu

TAG=${1:?usage: render.sh vX.Y.Z}
VER=${TAG#v}
REPO=https://github.com/emielvangoor/paseo-tui
DL=$REPO/releases/download/$TAG
DESC="Keyboard-first terminal client for Paseo coding agents"
ROOT=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
SUMS=$ROOT/dist/checksums.txt
OUT=$ROOT/dist/pkg

sha() {
  h=$(awk -v f="$1" '$2 == f || $2 == "*" f {print $1}' "$SUMS")
  [ -n "$h" ] || { echo "render.sh: $1 is not in checksums.txt" >&2; exit 1; }
  echo "$h"
}

case "$VER" in
  *-*) echo "render.sh: $TAG is a pre-release; package managers only get stable releases" >&2; exit 1 ;;
esac

mkdir -p "$OUT/homebrew" "$OUT/scoop" "$OUT/aur"

cat > "$OUT/homebrew/paseo-tui.rb" <<EOF
# Generated by the paseo-tui release workflow; don't edit by hand.
class PaseoTui < Formula
  desc "$DESC"
  homepage "$REPO"
  version "$VER"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$DL/paseo-tui_darwin_arm64.tar.gz"
      sha256 "$(sha paseo-tui_darwin_arm64.tar.gz)"
    end
    on_intel do
      url "$DL/paseo-tui_darwin_amd64.tar.gz"
      sha256 "$(sha paseo-tui_darwin_amd64.tar.gz)"
    end
  end

  on_linux do
    on_arm do
      url "$DL/paseo-tui_linux_arm64.tar.gz"
      sha256 "$(sha paseo-tui_linux_arm64.tar.gz)"
    end
    on_intel do
      url "$DL/paseo-tui_linux_amd64.tar.gz"
      sha256 "$(sha paseo-tui_linux_amd64.tar.gz)"
    end
  end

  def install
    bin.install "paseo-tui"
  end

  def caveats
    <<~EOS
      paseo-tui needs a Paseo daemon (the Paseo desktop app runs one) and a JavaScript
      runtime: node on your PATH, or the runtime inside the Paseo app.
    EOS
  end

  test do
    assert_match "paseo-tui v#{version}", shell_output("#{bin}/paseo-tui --version")
  end
end
EOF

cat > "$OUT/scoop/paseo-tui.json" <<EOF
{
  "version": "$VER",
  "description": "$DESC",
  "homepage": "$REPO",
  "license": "Apache-2.0",
  "notes": "paseo-tui needs a Paseo daemon (the Paseo desktop app runs one) and Node.js or the Paseo app.",
  "architecture": {
    "64bit": {
      "url": "$DL/paseo-tui_windows_amd64.zip",
      "hash": "$(sha paseo-tui_windows_amd64.zip)",
      "extract_dir": "paseo-tui_windows_amd64"
    },
    "arm64": {
      "url": "$DL/paseo-tui_windows_arm64.zip",
      "hash": "$(sha paseo-tui_windows_arm64.zip)",
      "extract_dir": "paseo-tui_windows_arm64"
    }
  },
  "bin": "paseo-tui.exe",
  "checkver": "github",
  "autoupdate": {
    "architecture": {
      "64bit": {
        "url": "$REPO/releases/download/v\$version/paseo-tui_windows_amd64.zip",
        "extract_dir": "paseo-tui_windows_amd64"
      },
      "arm64": {
        "url": "$REPO/releases/download/v\$version/paseo-tui_windows_arm64.zip",
        "extract_dir": "paseo-tui_windows_arm64"
      }
    },
    "hash": {
      "url": "\$baseurl/checksums.txt"
    }
  }
}
EOF

AMD64=$(sha paseo-tui_linux_amd64.tar.gz)
ARM64=$(sha paseo-tui_linux_arm64.tar.gz)

cat > "$OUT/aur/PKGBUILD" <<EOF
# Maintainer: Emiel van Goor <1568041+emielvangoor@users.noreply.github.com>
# Generated by the paseo-tui release workflow: $REPO
pkgname=paseo-tui-bin
pkgver=$VER
pkgrel=1
pkgdesc="$DESC"
arch=('x86_64' 'aarch64')
url="$REPO"
license=('Apache-2.0')
provides=('paseo-tui')
conflicts=('paseo-tui')
optdepends=('nodejs: JavaScript runtime for the bridge (or install the Paseo app)'
            'wl-clipboard: paste images on Wayland'
            'xclip: paste images on X11')
options=('!strip' '!debug')
source_x86_64=("paseo-tui-\${pkgver}-x86_64.tar.gz::\${url}/releases/download/v\${pkgver}/paseo-tui_linux_amd64.tar.gz")
source_aarch64=("paseo-tui-\${pkgver}-aarch64.tar.gz::\${url}/releases/download/v\${pkgver}/paseo-tui_linux_arm64.tar.gz")
sha256sums_x86_64=('$AMD64')
sha256sums_aarch64=('$ARM64')

package() {
  local goarch=amd64
  [ "\$CARCH" = aarch64 ] && goarch=arm64
  cd "paseo-tui_linux_\${goarch}"
  install -Dm755 paseo-tui "\$pkgdir/usr/bin/paseo-tui"
  install -Dm644 LICENSE "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE"
  install -Dm644 NOTICE "\$pkgdir/usr/share/licenses/\$pkgname/NOTICE"
  install -Dm644 README.md "\$pkgdir/usr/share/doc/\$pkgname/README.md"
}
EOF

# The same as \`makepkg --printsrcinfo\`, which isn't available on the Ubuntu runners.
TAB=$(printf '\t')
cat > "$OUT/aur/.SRCINFO" <<EOF
pkgbase = paseo-tui-bin
${TAB}pkgdesc = $DESC
${TAB}pkgver = $VER
${TAB}pkgrel = 1
${TAB}url = $REPO
${TAB}arch = x86_64
${TAB}arch = aarch64
${TAB}license = Apache-2.0
${TAB}optdepends = nodejs: JavaScript runtime for the bridge (or install the Paseo app)
${TAB}optdepends = wl-clipboard: paste images on Wayland
${TAB}optdepends = xclip: paste images on X11
${TAB}provides = paseo-tui
${TAB}conflicts = paseo-tui
${TAB}options = !strip
${TAB}options = !debug
${TAB}source_x86_64 = paseo-tui-$VER-x86_64.tar.gz::$DL/paseo-tui_linux_amd64.tar.gz
${TAB}sha256sums_x86_64 = $AMD64
${TAB}source_aarch64 = paseo-tui-$VER-aarch64.tar.gz::$DL/paseo-tui_linux_arm64.tar.gz
${TAB}sha256sums_aarch64 = $ARM64

pkgname = paseo-tui-bin
EOF

echo "==> manifests for $TAG in dist/pkg/"
